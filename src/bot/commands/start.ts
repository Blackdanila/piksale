import type { Context } from "grammy";
import { mainMenu } from "../keyboards.js";

export async function handleStart(ctx: Context) {
  await ctx.reply(
    [
      "👋 Привет! Я PIKsale — слежу за ценами на квартиры ПИК.",
      "",
      "Цены обновляются каждый день в 08:00 МСК.",
      "",
      "Что я умею:",
      "🔍 <b>Поиск</b> — квартиры по городу, комнатности и бюджету",
      "🏢 <b>Каталог ЖК</b> — все ЖК города с ценой от и числом квартир",
      "📊 <b>Динамика</b> — как менялась цена ₽/м² по ЖК и городу",
      "🔔 <b>Мои подписки</b> — уведомления об изменении цен в ваших ЖК",
      "",
      "Выберите действие в меню 👇",
    ].join("\n"),
    { reply_markup: mainMenu, parse_mode: "HTML" },
  );
}

